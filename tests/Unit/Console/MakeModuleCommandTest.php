    }

    /**
     * @param  array<string, string>  $input
     */
    private function runMakeModule(array $input): CommandTester
    {
        $application = new Application();
        $application->add(new MakeModuleCommand());

        $commandTester = new CommandTester($application->find('make:module'));
        $commandTester->execute($input);

        return $commandTester;
    }

    private function lint(string $file): int
    {
        exec(sprintf('%s -l %s 2>&1', escapeshellarg(PHP_BINARY), escapeshellarg($file)), $ignored, $exitCode);

        return $exitCode;
    }

    private function removeDirectory(string $dir): void
    {
        if (! is_dir($dir)) {
            return;
        }

        $files = array_diff(scandir($dir), ['.', '..']);
        foreach ($files as $file) {
            $path = sprintf('%s/%s', $dir, $file);
            is_dir($path) ? $this->removeDirectory($path) : unlink($path);
        }

        rmdir($dir);
    }
}
