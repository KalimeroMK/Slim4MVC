<?php

declare(strict_types=1);

namespace Tests\Unit\Console;

use App\Console\Commands\MakeModuleCommand;
use PHPUnit\Framework\TestCase;
use Symfony\Component\Console\Application;
use Symfony\Component\Console\Tester\CommandTester;

/**
 * make:module writes into the real project tree, so every bootstrap file it edits is
 * snapshotted here and restored byte-for-byte afterwards. Regex-based cleanup used to
 * leave `];` glued to the previous entry, which the next run then appended to —
 * corrupting bootstrap/dependencies.php a little more on every test run.
 */
final class MakeModuleCommandTest extends TestCase
{
    /**
     * Project files make:module is allowed to touch, relative to the project root.
     */
    private const array MUTABLE_FILES = [
        'bootstrap/dependencies.php',
        'bootstrap/modules-register.php',
    ];

    /**
     * Module directories generated by these tests, relative to the project root.
     */
    private const array GENERATED_MODULES = [
        'app/Modules/TestModule',
        'app/Modules/Product',
    ];

    private string $projectRoot;

    private string $testModulePath;

    /** @var array<string, string|null> absolute path => original contents (null when absent) */
    private array $snapshots = [];

    protected function setUp(): void
    {
        parent::setUp();
        // Get project root (3 levels up from tests/Unit/Console)
        $this->projectRoot = dirname(__DIR__, 3);
        $this->testModulePath = $this->projectRoot.'/app/Modules/TestModule';

        foreach (self::MUTABLE_FILES as $relative) {
            $path = $this->projectRoot.'/'.$relative;
            $this->snapshots[$path] = file_exists($path) ? (string) file_get_contents($path) : null;
        }
    }

    protected function tearDown(): void
    {
        foreach (self::GENERATED_MODULES as $relative) {
            $this->removeDirectory($this->projectRoot.'/'.$relative);
        }

        foreach ($this->snapshots as $path => $original) {
            if ($original === null) {
                if (file_exists($path)) {
                    unlink($path);
                }

                continue;
            }

            file_put_contents($path, $original);
        }

        $this->snapshots = [];

        parent::tearDown();
    }

    public function test_generated_dependencies_file_stays_valid_php(): void
    {
        $this->runMakeModule(['name' => 'TestModule']);

        $depsFile = $this->projectRoot.'/bootstrap/dependencies.php';

        $this->assertSame(
            0,
            $this->lint($depsFile),
            'make:module must leave bootstrap/dependencies.php syntactically valid.'
        );
    }

    public function test_generated_entries_do_not_glue_onto_the_closing_bracket(): void
    {
        $this->runMakeModule(['name' => 'TestModule']);

        $content = (string) file_get_contents($this->projectRoot.'/bootstrap/dependencies.php');

        $this->assertMatchesRegularExpression(
            '/,\s*\n\];/',
            $content,
            'The array closing bracket must keep its own line.'
        );
        $this->assertDoesNotMatchRegularExpression(
            '/\)\s{2,}\w+ActionInterface::class/',
            $content,
            'A generated entry must not share a line with the preceding entry.'
        );
    }

    public function test_repeated_runs_do_not_accumulate_duplicate_entries(): void
    {
        $this->runMakeModule(['name' => 'TestModule']);
        $this->removeDirectory($this->testModulePath);
        $this->runMakeModule(['name' => 'TestModule']);

        $content = (string) file_get_contents($this->projectRoot.'/bootstrap/dependencies.php');

        $this->assertSame(
            1,
            substr_count($content, 'CreateTestModuleActionInterface::class =>'),
            'An interface already present must not be registered twice.'
        );
    }

    public function test_make_module_creates_directory_structure(): void
    {
        $application = new Application();
        $application->add(new MakeModuleCommand());

        $command = $application->find('make:module');
        $commandTester = new CommandTester($command);

        $commandTester->execute(['name' => 'TestModule']);

        $this->assertDirectoryExists($this->testModulePath.'/Application/Actions');
        $this->assertDirectoryExists($this->testModulePath.'/Application/DTOs');
        $this->assertDirectoryExists($this->testModulePath.'/Infrastructure/Models');
        $this->assertDirectoryExists($this->testModulePath.'/Infrastructure/Repositories');
        $this->assertDirectoryExists($this->testModulePath.'/Infrastructure/Http/Controllers');
        $this->assertDirectoryExists($this->testModulePath.'/Infrastructure/Routes');
        $this->assertDirectoryExists($this->testModulePath.'/Policies');
    }

    public function test_make_module_creates_all_required_files(): void
